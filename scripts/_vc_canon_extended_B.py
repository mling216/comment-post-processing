def resolve_object_synset_extended(name: str) -> str:
    """Like resolve_object_synset but also checks EXTENDED_SYNSETS."""
    base = _base_resolve(name)
    if not base.startswith("unknown."):
        return base
    # Normalise the same way _vc_canon does
    norm = (name or "").strip().lower().replace(" ", "_").replace("-", "_")
    return EXTENDED_SYNSETS.get(norm, base)
